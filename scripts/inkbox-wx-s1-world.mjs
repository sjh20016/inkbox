import assert from 'node:assert/strict';
import {worldObjectStoryCandidates as read} from '../src/inkbox/wanxiang/storyWorld.js';
import {forgeArtifact,toGround,claimGroundArtifact,stepArtifacts} from '../src/inkbox/sim/artifacts.js';
import {settlementHistory,archiveSettlement,damageSettlement,aidSettlement} from '../src/inkbox/sim/settlementResilience.js';
import {World} from '../src/inkbox/world/World.js';
import {TERRAIN} from '../src/inkbox/core/config.js';
const w=new World(32,32,73101);w.day=360;
const owner={id:1,name:'同名',sp:'cultivator',level:8,hp:100,x:4,y:4,artifacts:[],relations:new Map()};
const taker={...owner,id:2,artifacts:[]};w.entities.push(owner,taker);
const a=forgeArtifact(w,owner,()=>.6,{slot:'武器'});assert(a);
const ref={kind:'artifact',plane:'mortal',id:a.id};
w.day=720;toGround(w,a,4,4);
assert.equal(read(w,ref).cards[0].related.length,1,'historical names must not create old-owner links');
w.day=1080;assert(claimGroundArtifact(w,taker,a.id,()=>.6));
let card=read(w,ref).cards[0];assert.equal(card.related[1].id,2);assert(card.nodes.length>=2);
const before=JSON.stringify(w);for(let i=0;i<100;i++)assert.deepEqual(read(w,ref).cards[0],card);assert.equal(JSON.stringify(w),before);
const upper=new World(32,32,42);upper.entities.push({...taker,id:1,artifacts:[a]});w.upper=upper;
assert.equal(read(w,ref).cards.length,0,'duplicate canonical object ownership must fail closed');
upper.entities[0].artifacts=[];taker.artifacts=[];upper.entities[0].artifacts=[a];a.ownerId=1;
assert.match(read(w,ref).stats.reason,/跨界/,'stale plane cannot silently adopt a new plane');
assert.equal(read(w,{...ref,plane:'upper'}).cards[0].related[1].plane,'upper');
upper.entities[0].artifacts=[];taker.artifacts=[a];a.ownerId=taker.id;
a.history.push([w.day+1,'found','未来同名']);assert(!read(w,ref).cards[0].nodes.some(n=>n.text.includes('未来')));a.history.pop();
upper.entities[0].artifacts=[];
toGround(w,a,4,4);w.day+=300*360;stepArtifacts(w,360,()=>.9);
assert.equal(read(w,ref).cards.length,0);assert.match(read(w,ref).stats.reason,/不能判定是否朽坏/);
const v={id:7,name:'同名村',x:16,y:16,hp:80,food:10,pop:3,houses:[],history:[],faction:0,foundedDay:0};w.villages.push(v);
settlementHistory(w,v,'founded','新村成立');
assert.equal(read(w,{kind:'settlement',plane:'mortal',id:7}).cards.length,0,'founded-only villages do not open a crisis hook');
assert(damageSettlement(w,v,{hp:20,reason:'地震'}));
card=read(w,{kind:'settlement',plane:'mortal',id:7}).cards[0];assert.equal(card.status,'watching');assert.equal(card.evidence[0].type,'disaster');
w.type.fill(TERRAIN.GRASS);w.height.fill(.45);
const faction={id:1,name:'甲宗',villages:[7],stability:70,pop:3,war:new Set(),destroyedDay:-1,resources:{provisions:100,spiritStone:100}};
w.factions.push(faction);v.faction=1;w.day+=30;aidSettlement(w,v,30);
assert(v.aidSpentSpiritStone>0);assert(v.history.some(h=>h.type==='aid'&&h.factionId===1),'formal aid preserves faction identity');
settlementHistory(w,v,'aid','甲宗调拨物资',{id:1,name:'甲宗'});
settlementHistory(w,v,'aid','乙宗调拨物资',{id:2,name:'乙宗'});
settlementHistory(w,v,'recovered','聚落灾后恢复');
assert.equal(read(w,{kind:'settlement',plane:'mortal',id:7}).cards[0].status,'resolved');
settlementHistory(w,v,'disaster','同日再遭灾');
assert.equal(read(w,{kind:'settlement',plane:'mortal',id:7}).cards[0].status,'watching','earlier recovery cannot settle a subsequent crisis');
archiveSettlement(w,v,'灾后荒废');w.villages=[];
w.villages.push({...v,id:8,history:[]});
card=read(w,{kind:'settlement-ruin',plane:'mortal',id:7}).cards[0];
assert.equal(card.status,'interrupted');assert(!card.related.some(r=>r.id===8));assert.equal(card.related.filter(r=>r.kind==='faction').length,2);
assert.equal(read(w,{kind:'settlement',plane:'mortal',id:8}).cards.length,0);
const old=JSON.stringify(w);read(w,{kind:'settlement-ruin',plane:'mortal',id:7});assert.equal(JSON.stringify(w),old);
console.log('WX-S1 world: formal artifact forge/loss/claim/decay; current owner identity; duplicate rejection; disaster/recovery/archive; same-name and faction provenance; repeated observation purity passed');
