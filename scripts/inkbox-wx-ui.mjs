import assert from 'node:assert/strict';
import {fixture} from './inkbox-g1-fixtures.mjs';
import {createCharacterController} from '../src/inkbox/g1/characterRuntime.js';
import {serializeWorld} from '../src/inkbox/io/save.js';
import {createSandboxCharacterRuntime} from '../src/inkbox/g1/sandboxRuntime.js';
const f=fixture(),w=f.world,e=f.entity,key=`mortal:${e.id}`;
const c=createCharacterController({getWorld:()=>w});
assert.ok(c.select(key).ok);
const run=(type,extra={})=>c.handleMingpu({type,targetKey:key,...extra});
assert.ok(run('enable').ok);
assert.ok(w.wanxiang.enabled);
assert.ok(e.wanxiang);
let draft=run('begin').draft;
const operations=[{op:'set',field:'physique',value:{id:'wood',stage:1,inheritable:true}},{op:'add',field:'states',value:{id:'breakthrough_echo',durationDays:180}}];
const before=JSON.stringify(serializeWorld(w)),draws=f.draws();
assert.ok(run('preview',{draft,operations}).ok);
assert.equal(JSON.stringify(serializeWorld(w)),before,'preview must not write the world or streams');
assert.equal(f.draws(),draws);
w.day+=10;
const result=run('commit',{draft,operations});
assert.ok(result.ok,JSON.stringify(result));
assert.equal(e.wanxiang.physique.id,'wood');
assert.equal(e.wanxiang.states[0].expiresDay,w.day+180);
assert.equal(e.wanxiang.history.at(-1).source,'玩家改命');
assert.equal(run('commit',{draft,operations}).ok,false,'consumed draft cannot commit again');
draft=run('begin').draft;
e.wanxiang.revision++;
assert.equal(run('commit',{draft,operations}).ok,false,'changed profile invalidates draft');
draft=run('begin').draft;
const i=w.entities.indexOf(e);w.entities[i]={...e};
assert.equal(run('commit',{draft,operations}).ok,false,'same id replacement must not receive edit');
w.entities[i]=e;
c.close();assert.equal(run('commit',{draft,operations}).ok,false);
console.log('Wanxiang real controller begin/preview/commit, time advancement, RNG purity and identity checks passed');

// A paused-world edit must participate in the host's unsaved/save-revision guard.
const fresh=fixture(), dirty=[];let onMingpu;
const sb={world:fresh.world,qol:{markDirty:kind=>dirty.push(kind),noteRecent(){}}};
const runtime=createSandboxCharacterRuntime(sb,{render(_sb,_vm,_action,options){onMingpu=options.onMingpu;}});
const targetKey=`mortal:${fresh.entity.id}`;
runtime.open(targetKey);
assert.ok(onMingpu({type:'enable',targetKey}).ok);
assert.deepEqual(dirty,['intervention']);dirty.length=0;
const hostDraft=onMingpu({type:'begin',targetKey}).draft;
const hostOperations=[{op:'set',field:'physique',value:{id:'wood',stage:1}}];
assert.ok(onMingpu({type:'preview',targetKey,draft:hostDraft,operations:hostOperations}).ok);
assert.equal(dirty.length,0,'read and preview do not mark a world edit');
assert.ok(onMingpu({type:'commit',targetKey,draft:hostDraft,operations:hostOperations}).ok);
assert.deepEqual(dirty,['intervention']);
assert.equal(onMingpu({type:'commit',targetKey,draft:hostDraft,operations:hostOperations}).ok,false);
assert.equal(dirty.length,1,'rejected commit does not mark another revision');
console.log('Wanxiang host marks successful mutations dirty without dirtying previews or rejected commits');
