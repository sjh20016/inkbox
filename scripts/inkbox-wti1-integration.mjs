import assert from 'node:assert/strict';
import { createWti1Scene } from './fixtures/wti1-scene.mjs';
import { Life } from '../src/inkbox/sim/life.js';
import { mulberry32 } from '../src/inkbox/core/noise.js';
import { advanceWorld, createAdvanceState } from '../src/inkbox/sim/advance.js';
import { requestWanling } from '../src/inkbox/sim/wanling.js';
import { requestCargoJourney, requestPersonJourney, stepTransit } from '../src/inkbox/sim/transit.js';
import { activeJourneyForEntity, snapshotTransit } from '../src/inkbox/world/transitState.js';
import { snapshotWanling } from '../src/inkbox/world/wanlingState.js';
import { daoActivityFor, stepDaoTravel, stepDaoActivities } from '../src/inkbox/sim/daoActivities.js';
import { serializeWorld, deserializeWorld } from '../src/inkbox/io/save.js';
import { History } from '../src/inkbox/sim/powers.js';
import { applyTransitScenarioEdit } from '../src/inkbox/dev/transitScenario.js';

let {world:w,life,metadata:m}=createWti1Scene();let clock=createAdvanceState();
const advance=days=>{for(let i=0;i<days;i++)advanceWorld(w,1,{life,state:clock,riftActive:false});};
for(const form of ['deer','wolf'])assert(requestWanling(w,form,35,50).ok);
const oldJob=daoActivityFor(w,m.actors.flier);assert.equal(oldJob.stage,'travel');
applyTransitScenarioEdit(w,new History(),'cut');
const ship=requestCargoJourney(w,{fromVillageId:1,toVillageId:2,food:24});assert(ship.ok,ship.reason);
const flight=requestPersonJourney(w,{actorId:m.actors.flier,toVillageId:2});assert(flight.ok,flight.reason);
assert.equal(daoActivityFor(w,m.actors.flier).stage,'done','T0 immediately cancels the old DAO job');
assert.match(daoActivityFor(w,m.actors.flier).summary,/山海通衢/);
const peopleBefore=w.entities.map(e=>e.id);
const flier=w.entities.find(e=>e.id===m.actors.flier),position=[flier.x,flier.y];
assert.equal(flier.timer,0,'a cancelled DAO target must not survive the journey as a long ground intent');
assert.deepEqual([flier.tx,flier.ty],position,'old DAO ground destination is cleared when T0 takes ownership');
assert.equal(stepDaoTravel(w,life,flier,1),false);assert.deepEqual([flier.x,flier.y],position,'DAO cannot move a T0 actor');
let groundMoves=0;const realMove=life.moveTowards.bind(life);
life.moveTowards=(e,...args)=>{if(e.id===m.actors.flier&&activeJourneyForEntity(w,e.id))groundMoves++;return realMove(e,...args);};
advance(6);
for(let i=0;i<16&&ship.journey.legMode!=='water';i++)advance(1);
assert.equal(flight.journey.legMode,'air');assert.equal(flight.journey.status,'active');
assert.equal(ship.journey.legMode,'water');
assert.equal(groundMoves,0,'formal Life yields all ground locomotion throughout flight');
const firstHeal=w.wanling.jobs.filter(j=>j.actorId===m.actors.healer&&j.stage==='done'&&j.summary.includes('疗伤'));
assert.equal(firstHeal.length,1,'first formal treatment actually completes');
const payload=JSON.parse(JSON.stringify(serializeWorld(w)));
assert.equal(payload.v,11);assert.equal(payload.wanling.v,1);assert.equal(payload.transit.v,1);
assert(payload.entities.every(row=>row.length===72),'form remains append-only at column 71');
const old=w;
for(const block of ['wanling','transit']) {
  const bad=structuredClone(payload);bad[block].v=99;
  assert.throws(()=>{w=deserializeWorld(bad);});
  assert.equal(w,old,'failed import never replaces the current world');
}
w=deserializeWorld(payload);life=new Life(w,mulberry32(1234));clock=createAdvanceState();
assert.deepEqual(snapshotTransit(w),payload.transit);assert.deepEqual(snapshotWanling(w),payload.wanling);
assert.deepEqual(w.entities.map(e=>e.id),payload.entities.map(row=>row[0]),'both containers preserve exact saved entity IDs');
assert(peopleBefore.every(id=>w.entities.some(e=>e.id===id)),'all original people remain after the bounded journey interval');
const legacy=structuredClone(payload);delete legacy.wanling;delete legacy.transit;for(const row of legacy.entities)row.pop();
const oldV11=deserializeWorld(legacy);assert.equal(oldV11.wanling,undefined);assert.equal(oldV11.transit,undefined);
applyTransitScenarioEdit(w,new History(),'dam');advance(1);
let loadedShip=w.transit.journeys.find(j=>j.id===ship.journey.id);
assert.equal(loadedShip.status,'blocked');assert.equal(loadedShip.cargo.food,24);
const held={...loadedShip.position};advance(2);assert.deepEqual(loadedShip.position,held);
applyTransitScenarioEdit(w,new History(),'reopen');
for(let i=0;i<180&&loadedShip.status!=='arrived';i++)advance(1);
assert.equal(loadedShip.status,'arrived');assert.equal(loadedShip.cargo.food,0);
assert.equal(w.transit.ledger.delivered,24);
const beforeDelivery=w.villages[1].food;stepTransit(w);stepTransit(w);
assert.equal(w.villages[1].food,beforeDelivery,'same-time calls cannot settle cargo twice');
const air=w.transit.journeys.find(j=>j.id===flight.journey.id);
assert.equal(air.status,'arrived');assert.equal(w.entities.find(e=>e.id===m.actors.flier).village,1);
advance(Math.max(0,220-Math.floor(w.day)));
const treatments=w.wanling.jobs.filter(j=>j.actorId===m.actors.healer&&j.stage==='done'&&j.summary.includes('疗伤'));
const wards=w.wanling.jobs.filter(j=>j.actorId===m.actors.talisman&&j.stage==='done'&&j.summary.includes('护村符'));
assert(treatments.length>=2,'same alchemist completes a second real action through full Life');
assert(wards.length>=2,'same talisman cultivator completes a second longer-cooldown action');
assert(w.entities.find(e=>e.id===m.actors.flier));
const lastFlight=daoActivityFor(w,m.actors.flier);
assert(!activeJourneyForEntity(w,m.actors.flier));
const cargo=w.transit.ledger,heldFood=w.transit.journeys.reduce((n,j)=>n+j.cargo.food,0);
assert.equal(cargo.loaded,cargo.delivered+cargo.returned+cargo.lost+heldFood);
// Provide a new local injury after return; the same real person can work again.
const returned=w.entities.find(e=>e.id===m.actors.flier),nearby=w.entities.find(e=>e.sp==='human'&&e.village===2);
assert(returned&&nearby);Object.assign(nearby,{x:returned.x+.4,y:returned.y,hp:nearby.maxHp*.4});
w.day+=30;stepDaoActivities(w,life);const beforeHeal=nearby.hp;
assert.equal(daoActivityFor(w,returned.id).stage,'travel');
assert.equal(stepDaoTravel(w,life,returned,1),true);assert(nearby.hp>beforeHeal,'returned traveller completes a new local treatment');
// A legacy overlapping pair is reconciled before any DAO target or movement write.
const overlap=deserializeWorld(payload),actor=overlap.entities.find(e=>e.id===m.actors.flier);
const current=overlap.wanling.jobs.find(j=>j.actorId===actor.id);current.stage='travel';
let moved=false;
assert.equal(stepDaoTravel(overlap,{moveTowards(){moved=true;}},actor,1),false);
assert.equal(moved,false);assert.equal(current.stage,'done');
overlap.day+=30;stepDaoActivities(overlap,new Life(overlap,()=>.5));
assert(!overlap.wanling.jobs.some(j=>j.actorId===actor.id&&j.stage!=='done'));
console.log('WT-I1 joint integration passed',JSON.stringify({day:w.day,heals:treatments.length,wards:wards.length,
  ship:loadedShip.id,flight:air.id,ledger:cargo,returningActorJob:daoActivityFor(w,m.actors.flier),groundMoves}));
