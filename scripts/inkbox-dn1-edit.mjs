import assert from 'node:assert/strict';
import { World } from '../src/inkbox/world/World.js';
import { classify, qiAt } from '../src/inkbox/world/terrain.js';
import { netherWalkable } from '../src/inkbox/world/planes.js';
import { netherBankTiles, spawnNetherGhost, netherActivityTileValid, pickNetherSpatialTarget } from '../src/inkbox/sim/netherLife.js';
import { generateNetherWorld } from '../src/inkbox/world/worldgenNether.js';
import { worldStream, captureWorldStreams } from '../src/inkbox/sim/worldStreams.js';
import { createNetherTerrainEditor } from '../src/inkbox/world/netherTerrainEdit.js';

const world = new World(12, 12, 7);
world.plane = 'nether';
world.height.fill(0.4);
world.temp.fill(0.5);
world.moist.fill(0.4);
world.water[53] = 0.04;
world.riverBase[53] = 0.024;
for (let y = 0; y < world.h; y++) for (let x = 0; x < world.w; x++) {
  const i = y * world.w + x;
  world.type[i] = classify(world, x, y, i);
  world.qi[i] = qiAt(world, x, y, i);
}
const ghost = { id: 1, soulKind: 'ghost', x: 5.5, y: 5.5, tx: 5.5, ty: 5.5 };
const item = { id: 2, x: 5.5, y: 5.5, ownerId: 0 };
world.entities.push(ghost);
world.artifacts.push(item);
const before = world.height.slice();
const rng = world.rng?.state;
netherBankTiles(world);
const editor = createNetherTerrainEditor(world);
assert(editor.apply({ tool: 'raise', x: 5, y: 5, radius: 0 }).changed);
assert(world.height[65] > before[65]);
assert(editor.apply({ tool: 'lower', x: 5, y: 5, radius: 0 }).changed);
assert(editor.apply({ tool: 'flatten', x: 5, y: 5, radius: 0, value: 0.7 }).changed);
assert.equal(world.height[65], Math.fround(0.7));
assert(editor.apply({ tool: 'yin', x: 5, y: 5, radius: 0, strength: 0.2 }).changed);
assert(world.veg[65] > 0);
const result = editor.apply({ tool: 'river', x: 5, y: 5, radius: 0, strength: 0.04 });
assert.equal(result.moved, 2);
assert.equal(result.clearedTargets, 1);
assert.equal(world.riverBase[65], Math.fround(world.water[65] * 0.6));
assert(!netherWalkable(world, 65));
assert(netherWalkable(world, Math.floor(ghost.y) * world.w + Math.floor(ghost.x)));
assert(netherWalkable(world, Math.floor(item.y) * world.w + Math.floor(item.x)));
assert.notDeepEqual(Array.from(netherBankTiles(world)), []);
assert(editor.undo());
assert.equal(world.water[65], 0);
assert.equal(ghost.x, 5.5);
assert.equal(ghost.tx, 5.5);
assert(editor.redo());
assert.equal(world.water[65], Math.fround(0.04));
assert.equal(world.rng?.state, rng);
editor.cancel();
assert.deepEqual(world.height, before);
assert.equal(world.water[65], 0);
assert.equal(world.veg[65], 0);
assert.equal(ghost.x, 5.5);
assert.equal(item.x, 5.5);
assert.throws(() => editor.apply({ tool: 'raise', x: 1, y: 1 }));
const committed = createNetherTerrainEditor(world);
committed.apply({ tool: 'river', x: 5, y: 5, radius: 0 });
assert(committed.commit().changed);
const trapped = new World(3, 3, 9);
trapped.plane = 'nether';
trapped.height.fill(0.4);
trapped.temp.fill(0.5);
trapped.moist.fill(0.4);
for (let y = 0; y < 3; y++) for (let x = 0; x < 3; x++) {
  trapped.type[y * 3 + x] = classify(trapped, x, y, y * 3 + x);
}
trapped.entities.push({ id: 3, soulKind: 'ghost', x: 1.5, y: 1.5 });
const rejecting = createNetherTerrainEditor(trapped);
assert.throws(() => rejecting.apply({ tool: 'river', x: 1, y: 1, radius: 2, strength: 0.1 }), /No legal/);
assert.equal(trapped.water[4], 0);
assert.equal(trapped.entities[0].x, 1.5);
assert.throws(() => rejecting.apply({ tool: 'river', x: 1, y: 1, value: Infinity }));
const actual = generateNetherWorld({ seed: 17 });
const realGhost = spawnNetherGhost(actual, { soulId: 77 });
assert(realGhost);
const start = { x: realGhost.x, y: realGhost.y, tx: realGhost.tx, ty: realGhost.ty };
const stream = worldStream(actual, 'dn1-probe', 12345);
stream();
const streamsBefore = captureWorldStreams(actual);
const originalRandom = Math.random;
Math.random = () => { throw new Error('editor consumed Math.random'); };
try {
  const edit = createNetherTerrainEditor(actual);
  const result = edit.apply({ tool: 'river', x: Math.floor(start.x), y: Math.floor(start.y), radius: 0, strength: 0.08 });
  assert.equal(result.moved, 1);
  assert.equal(result.clearedTargets, 1);
  assert(Number.isNaN(realGhost.tx));
  assert(netherit(realGhost));
  edit.undo();
  assert.deepEqual({ x: realGhost.x, y: realGhost.y, tx: realGhost.tx, ty: realGhost.ty }, start);
  edit.redo();
  edit.cancel();
} finally { Math.random = originalRandom; }
assert.deepEqual(captureWorldStreams(actual), streamsBefore);
function netherit(o) { return netherWalkable(actual, Math.floor(o.y) * actual.w + Math.floor(o.x)); }
const drained = generateNetherWorld({ seed: 29 });
const stranded = spawnNetherGhost(drained, { soulId: 991 });
assert(stranded);
const home = { x: stranded.x, y: stranded.y, tx: stranded.tx, ty: stranded.ty };
const drainEdit = createNetherTerrainEditor(drained);
const drainedResult = drainEdit.apply({ tool: 'river', x: Math.floor(home.x), y: Math.floor(home.y), radius: 14, strength: 0 });
assert(drainedResult.moved > 0);
assert(netherWalkable(drained, Math.floor(home.y) * drained.w + Math.floor(home.x)));
assert(netherActivityTileValid(drained, stranded, stranded.x, stranded.y));
assert(pickNetherSpatialTarget(drained, stranded, 1, []));
drainEdit.cancel();
assert.deepEqual({ x: stranded.x, y: stranded.y, tx: stranded.tx, ty: stranded.ty }, home);
const fullDrain = createNetherTerrainEditor(drained);
assert.throws(() => fullDrain.apply({ tool: 'river', x: drained.w / 2, y: drained.h / 2,
  radius: drained.w + drained.h, strength: 0 }), /No legal/);
assert(netherActivityTileValid(drained, stranded, stranded.x, stranded.y));
fullDrain.cancel();
