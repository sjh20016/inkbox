empty.plane = 'nether';
empty.height.fill(0.4);
empty.temp.fill(0.5);
empty.moist.fill(0.4);
for (let y = 0; y < 3; y++) for (let x = 0; x < 3; x++)
  empty.type[y * 3 + x] = classify(empty, x, y, y * 3 + x);
const emptyEdit = createNetherTerrainEditor(empty);
assert(emptyEdit.apply({ tool: 'raise', x: 1, y: 1, radius: 0 }).changed);
emptyEdit.cancel();
