import assert from 'node:assert/strict';
import {configureFrameBreakdown,beginBreakdown,endBreakdown,markBreakdown,snapshotFrameBreakdown} from '../src/inkbox/dev/frameBreakdown.js';
assert.equal(beginBreakdown('disabled'), null);
assert.equal(snapshotFrameBreakdown().samples.length, 0);
configureFrameBreakdown({enabled:true,capacity:10});
const parent=beginBreakdown('parent'),child=beginBreakdown('child');
endBreakdown(child);markBreakdown('event',{cacheHit:true});endBreakdown(parent);
let snapshot=snapshotFrameBreakdown();
assert.equal(snapshot.activeSpans,0);
assert.equal(snapshot.samples[0].parentId,parent.id);
assert(snapshot.samples[2].inclusiveMs>=snapshot.samples[0].inclusiveMs);
assert(Math.abs(snapshot.samples[2].exclusiveMs+snapshot.samples[0].inclusiveMs-snapshot.samples[2].inclusiveMs)<1e-7);
snapshot.samples.length=0;assert.equal(snapshotFrameBreakdown().samples.length,3);
assert.throws(()=>configureFrameBreakdown({enabled:true,capacity:2,reset:false}),/requires a reset/);
assert.equal(snapshotFrameBreakdown().capacity,10);
assert.equal(snapshotFrameBreakdown().samples.length,3);
const outer=beginBreakdown('exception'),inner=beginBreakdown('unfinished');
endBreakdown(outer,{failed:true});snapshot=snapshotFrameBreakdown();
assert.equal(snapshot.activeSpans,0);assert(snapshot.samples.some(s=>s.id===inner.id&&s.interrupted));
configureFrameBreakdown({enabled:true,capacity:2});
for(let i=0;i<4;i++)markBreakdown('bounded',{i});
assert.deepEqual(snapshotFrameBreakdown().samples.map(s=>s.i),[2,3]);
assert.equal(snapshotFrameBreakdown().dropped,2);
configureFrameBreakdown({enabled:false});assert.equal(beginBreakdown('off'),null);
console.log('E-M2 breakdown: default off, nesting/exclusive wall, exception unwind, bounded ordered raw samples pass');
