import assert from 'node:assert/strict';
import {emptyProfile,validateProfile} from '../src/inkbox/wanxiang/profile.js';
import {reduceIncomingDamage,postCombatHit,battleBonus,manaCapacity} from '../src/inkbox/wanxiang/damage.js';
import {combatState,equipSkills,chooseSkillAction} from '../src/inkbox/wanxiang/skills.js';
import {MANUALS} from '../src/inkbox/core/lore.js';
const actor=(id,physique=null)=>({id,hp:100,maxHp:100,level:10,x:0,y:0,plane:0,techniques:[],wanxiang:{...emptyProfile(),physique:physique?{id:physique}:null}});
const a=actor(1),b=actor(2,'spell_ward'),w={day:1,entities:[a,b],wanxiang:{enabled:true}};
const hit=(kind,n=100)=>reduceIncomingDamage(a,b,n,kind,w);
assert.equal(hit('spell'),75);assert.ok(Math.abs(hit('physical')-115)<1e-9);assert.equal(hit('true'),100);
b.wanxiang.physique={id:'earth'};assert.equal(hit('spell'),85);assert.equal(hit('physical'),85);
b.wanxiang.physique=null;a.wanxiang.physique={id:'solar'};
assert.equal(reduceIncomingDamage(a,b,100,'spell',w,{element:'yang',skill:'yang'}),100);
a.techniques=[MANUALS.find(t=>t.kind==='dual')];assert.equal(equipSkills(a,['yang']),true);
const yang=chooseSkillAction(a,b,w.day,{power:1,defense:0});assert.equal(yang.element,'yang');
assert.ok(Math.abs(reduceIncomingDamage(a,b,100,yang.kind,w,yang)-112)<1e-9);
assert.equal(reduceIncomingDamage(a,b,100,'physical',w,yang),100);
a.wanxiang.physique={id:'thunder'};a.techniques=[MANUALS.find(t=>t.kind==='thunder')];assert.equal(equipSkills(a,['thunder']),true);
assert.ok(Math.abs(reduceIncomingDamage(a,b,100,'spell',w,{skill:'thunder',element:'thunder'})-112)<1e-9);
a.wanxiang.physique={id:'devour'};assert.equal(manaCapacity(a),18);combatState(a).mana=5;combatState(b).mana=10;
b.hp=90;
const packet={amount:10,hpBefore:100,kind:'spell'};
assert.equal(postCombatHit(w,a,b,packet).drained,2);assert.equal(combatState(a).mana,7);assert.equal(combatState(b).mana,8);
assert.equal(postCombatHit(w,a,b,packet).drained,0);
w.day=2;assert.equal(postCombatHit(w,a,b,{...packet,sparring:true}).drained,0);
a.wanxiang.physique=null;a.wanxiang.bloodlines=[{id:'asura',grade:1,purity:100,latent:false}];
assert.equal(postCombatHit(w,a,b,packet).asura,true);assert.equal(postCombatHit(w,a,b,packet).asura,false);assert.equal(battleBonus(a,w.day),.02);
for(let id=3;id<=5;id++){const t=actor(id);t.hp=90;w.entities.push(t);postCombatHit(w,a,t,packet);}
assert.equal(a.wanxiang.cultivation.battle.grants,3);assert.equal(battleBonus(a,w.day),.06);
assert.equal(battleBonus(a,w.day+30),0);
const weak=actor(6);weak.level=1;weak.hp=90;w.entities.push(weak);w.day+=360;
assert.equal(postCombatHit(w,a,weak,packet).asura,false);
assert.equal(postCombatHit(w,a,b,{amount:0,hpBefore:90}).asura,false);
validateProfile(JSON.parse(JSON.stringify(a.wanxiang)));
w.wanxiang.enabled=false;assert.equal(reduceIncomingDamage(a,b,100,'spell',w),100);
console.log('wx damage: typed costs, qualified elemental skills, conserved drain, strong-opponent bounded asura, expiry and serialization passed');
