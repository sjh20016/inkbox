import assert from 'node:assert/strict';
import {stepDaoActivities,stepDaoTravel,daoActivityFor} from '../src/inkbox/sim/daoActivities.js';
import {wanlingState,snapshotWanling,restoreWanling} from '../src/inkbox/world/wanlingState.js';
import {emptyProfile} from '../src/inkbox/wanxiang/profile.js';
import {expToNext} from '../src/inkbox/core/cultivation.js';
import {readEffects} from '../src/inkbox/wanxiang/effects.js';
import {invalidateTransitGeography} from '../src/inkbox/world/transitGeography.js';

const w=10,h=10,struct=new Uint8Array(w*h);
const person=(id,x,hp,path)=>({id,name:`修士${id}`,sp:'cultivator',x,y:3,tx:x,ty:3,hp,maxHp:100,level:5,exp:0,
 incarnation:1,dao:{path:{key:path}},wanxiang:emptyProfile(),relations:new Map()});
const healer=person(1,3,100,'alchemy'),patient=person(2,4,60,'body');
const world={day:30,plane:'mortal',w,h,size:w*h,struct,water:new Float32Array(w*h),entities:[healer,patient],villages:[],sites:[],ruins:[],artifacts:[],wraiths:[],factions:[],
 wanxiang:{enabled:true,wxCEnabled:true},isWalkable:i=>i>=0&&i<w*h,record(){}};
const life={moveTowards(){}};
wanlingState(world).lastPathDay=0;
assert.equal(stepDaoActivities(world,life),1);
assert.equal(daoActivityFor(world,1).path,'alchemy');
assert.equal(stepDaoTravel(world,life,healer,1),true);
assert.ok(patient.hp>60);
assert.ok(patient.wanxiang.bonds.some(b=>b.id==='gratitude:mortal:1'));

healer.hp=70;world.day=60;
assert.equal(stepDaoActivities(world,life),1);
let job=daoActivityFor(world,2);
assert.equal(job.path,'social');assert.equal(job.intent,'heal');
const beforeHp=patient.hp,previous=healer.hp;
assert.equal(stepDaoTravel(world,life,patient,1),true);
assert.ok(healer.hp>previous&&patient.hp<beforeHp);
job=daoActivityFor(world,2);assert.equal(job.stage,'done');assert.equal(job.cost.kind,'actor-hp');
assert.ok(patient.wanxiang.history.some(h=>h.type==='报偿恩义'&&h.cost?.amount>0));

world.day=800;healer.hp=100;healer.exp=expToNext(healer.level)*.8;
assert.ok(stepDaoActivities(world,life)>=1);
job=daoActivityFor(world,2);assert.equal(job.intent,'guard');
const snapshot=snapshotWanling(world);restoreWanling(world,snapshot);
assert.equal(stepDaoTravel(world,life,patient,1),true);
assert.ok(healer.wanxiang.states.some(s=>s.id==='alchemy_guard'));
assert.ok(daoActivityFor(world,2).cost.amount>0);
world.day=1600;healer.hp=60;
assert.ok(stepDaoActivities(world,life)>=1);
assert.equal(daoActivityFor(world,2).stage,'travel');
patient.wanxiang.bonds.find(b=>b.id==='gratitude:mortal:1').dormant=true;
assert.equal(stepDaoTravel(world,life,patient,1),false);
assert.equal(daoActivityFor(world,2).stage,'done');
assert.match(daoActivityFor(world,2).summary,/关系或身份失效/);
assert.equal(daoActivityFor(world,2).reason,'withdrawn');
world.day=2400;healer.hp=60;patient.hp=1;
patient.wanxiang.bonds.find(b=>b.id==='gratitude:mortal:1').dormant=false;
assert.ok(stepDaoActivities(world,life)>=1);
assert.equal(daoActivityFor(world,2).intent,'heal');
const unpaidHp=healer.hp;
assert.equal(stepDaoTravel(world,life,patient,1),true);
assert.equal(healer.hp,unpaidHp,'unaffordable assistance cannot heal');
world.day=2500;assert.equal(stepDaoTravel(world,life,patient,1),false);
assert.equal(daoActivityFor(world,2).reason,'failed');
const chooser=person(4,4,100,'body'),left=person(5,3,60,'body'),right=person(6,5,60,'body');
chooser.wanxiang.bonds=[left,right].map(t=>({id:`gratitude:mortal:${t.id}`,targetKey:`mortal:${t.id}`,expiresDay:3600}));
chooser.relations.set(right.id,{type:'mentor',score:50});chooser.wanxiang.hexagram={id:'hex_13'};
const selectionWorld={...world,day:30,entities:[chooser,left,right],wanling:undefined,wanxiang:{enabled:true,wxCEnabled:true}};
wanlingState(selectionWorld).lastPathDay=0;
assert(readEffects(chooser,{world:selectionWorld,target:right,paidAid:true}).aidIntent>readEffects(chooser,{world:selectionWorld,target:left,paidAid:true}).aidIntent);
stepDaoActivities(selectionWorld,life);
assert.equal(daoActivityFor(selectionWorld,chooser.id).targetId,right.id,'hexagram aid axis changes a lawful target choice');
right.x=6;
invalidateTransitGeography(selectionWorld);
assert.equal(stepDaoTravel(selectionWorld,life,chooser,1),true);
assert.equal(daoActivityFor(selectionWorld,chooser.id).corners.at(-1).x,6,'moving target replans the route');
selectionWorld.struct[3*w+5]=3;
invalidateTransitGeography(selectionWorld);
assert.equal(stepDaoTravel(selectionWorld,life,chooser,1),true);
assert.ok(daoActivityFor(selectionWorld,chooser.id).corners.some(c=>c.y!==3),'terrain change replans a lawful detour');
selectionWorld.day=400;
assert.equal(stepDaoTravel(selectionWorld,life,chooser,1),false);
assert.equal(daoActivityFor(selectionWorld,chooser.id).reason,'timeout');
const sectHealer=person(10,4,100,'alchemy'),stranger=person(11,5,60,'body'),sectPatient=person(12,5.1,60,'body');
sectHealer.faction=7;sectPatient.faction=7;
const sect={id:7,resources:{spiritStone:1}};
const sectWorld={...world,day:30,entities:[sectHealer,stranger,sectPatient],factions:[sect],wanling:undefined,wanxiang:{enabled:true,wxCEnabled:true}};
wanlingState(sectWorld).lastPathDay=0;
assert.equal(stepDaoActivities(sectWorld,life),1);
assert.equal(daoActivityFor(sectWorld,sectHealer.id).targetId,sectPatient.id);
assert.equal(stepDaoTravel(sectWorld,life,sectHealer,1),true);
assert.equal(sect.resources.spiritStone,.8);
assert.ok(sectHealer.wanxiang.history.some(h=>h.type==='同宗照护'&&h.cost?.kind==='sect-spirit-stone'));
sect.resources.spiritStone=0;sectHealer.hp=1;sectPatient.hp=60;stranger.hp=100;sectWorld.day=130;
sectWorld.wanling.lastPathDay=0;
stepDaoActivities(sectWorld,life);
assert.equal(stepDaoTravel(sectWorld,life,sectHealer,1),true);
assert.equal(sectPatient.hp,60,'sect depletion and exhausted healer cannot provide free treatment');
const guardian=person(20,3,100,'body'),ward=person(21,4,100,'body');
ward.exp=expToNext(ward.level)*.8;
guardian.wanxiang.bonds=[{id:'gratitude:mortal:21',targetKey:'mortal:21',expiresDay:3600}];
ward.wanxiang.states=Array.from({length:32},(_,i)=>({id:`occupied_${i}`,expiresDay:3600}));
const fullWorld={...world,day:30,entities:[guardian,ward],wanling:undefined,wanxiang:{enabled:true,wxCEnabled:true}};
wanlingState(fullWorld).lastPathDay=0;
assert.equal(stepDaoActivities(fullWorld,life),1);
const beforeGuardHp=guardian.hp,beforeFact=fullWorld.wanxiang.factSequence||0;
assert.equal(stepDaoTravel(fullWorld,life,guardian,1),true);
assert.equal(guardian.hp,beforeGuardHp);
assert.equal(fullWorld.wanxiang.factSequence||0,beforeFact);
assert.equal(ward.wanxiang.states.length,32);
fullWorld.day=130;assert.equal(stepDaoTravel(fullWorld,life,guardian,1),false);
assert.equal(daoActivityFor(fullWorld,guardian.id).reason,'failed');
fullWorld.day=800;ward.wanxiang.states[0].expiresDay=700;
assert.equal(stepDaoActivities(fullWorld,life),1);
const payableHp=guardian.hp;
assert.equal(stepDaoTravel(fullWorld,life,guardian,1),true);
assert.ok(guardian.hp<payableHp);
assert.ok(ward.wanxiang.states.some(s=>s.id==='alchemy_guard'&&s.expiresDay>fullWorld.day),
  'expired occupant permits one paid, effective guard state');
console.log('WX-D real healing -> gratitude -> paid reciprocal healing -> paid gate aid passed');
